#!/usr/bin/env node
/**
 * bundle.mjs — headless Luau test harness for Sanctum of Embers.
 *
 * Roblox source under src/ cannot be run by the stock `luau` CLI: it uses `game:GetService`,
 * Instance trees and `require(script.Parent.X)`, none of which exist outside Roblox. This tool
 * bridges that gap without any Roblox dependency:
 *
 *   1. Walk src/ and map every .luau file to the instance path Rojo would give it.
 *   2. Wrap each file's source in `function(script, require, ...) <source> end` so `script` and
 *      `require` become ordinary parameters supplied by the mock at call time.
 *   3. Concatenate: mock environment  ->  module registry  ->  test framework  ->  spec bodies.
 *   4. Pipe the result to `luau`, which compiles it as one chunk (so any syntax error in any
 *      source file fails the build) and runs it.
 *
 * The only source rewrite is stripping a leading `export ` from `export type` — Luau allows
 * exported type aliases at module scope only, and wrapping puts them inside a function body.
 * Exported types are editor-time only, so removing the keyword cannot change runtime behaviour.
 *
 * Usage:  node tests/tools/bundle.mjs [--emit <file>] [--only <substr>] [spec ...]
 */

import { readFileSync, writeFileSync, readdirSync, statSync, mkdirSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { dirname, join, relative, resolve, basename } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const SRC = join(ROOT, "src");
const MOCK_DIR = join(ROOT, "tests", "mock");
const SPEC_DIR = join(ROOT, "tests", "specs");
const LUAU = process.env.LUAU_BIN || "luau";

/** Rojo maps these source roots onto these instance paths (mirrors default.project.json). */
const ROOTS = [
    { dir: "shared", instance: "ReplicatedStorage/Modules" },
    { dir: "server", instance: "ServerScriptService/Core" },
    { dir: "client", instance: "StarterPlayer/StarterPlayerScripts/Client" },
];

function walk(dir, out = []) {
    let entries;
    try {
        entries = readdirSync(dir);
    } catch {
        return out;
    }
    for (const entry of entries.sort()) {
        const full = join(dir, entry);
        const st = statSync(full);
        if (st.isDirectory()) walk(full, out);
        else if (entry.endsWith(".luau")) out.push(full);
    }
    return out;
}

/** `src/server/Services/PlotService.luau` -> { path, class } as Rojo would name it. */
function classify(file) {
    const rel = relative(SRC, file).split("/");
    const rootDir = rel.shift();
    const root = ROOTS.find((r) => r.dir === rootDir);
    if (!root) return null;

    let name = rel.pop().replace(/\.luau$/, "");
    let cls = "ModuleScript";
    if (name.endsWith(".server")) {
        cls = "Script";
        name = name.slice(0, -".server".length);
    } else if (name.endsWith(".client")) {
        cls = "LocalScript";
        name = name.slice(0, -".client".length);
    }

    // `Foo/init.luau` collapses into the `Foo` instance itself, as Rojo does.
    const segments = [root.instance, ...rel];
    const path = name === "init" ? segments.join("/") : [...segments, name].join("/");
    return { path, class: cls, file };
}

function luaLongString(text) {
    // Pick an `=` level the payload cannot terminate early.
    let level = 0;
    while (text.includes("]" + "=".repeat(level) + "]")) level += 1;
    const eq = "=".repeat(level);
    return `[${eq}[\n${text}\n]${eq}]`;
}

/** Strip `export ` from exported type aliases; everything else is passed through verbatim. */
function prepare(source) {
    return source.replace(/^(\s*)export\s+type\s/gm, "$1type ");
}

const modules = walk(SRC).map(classify).filter(Boolean);
if (modules.length === 0) {
    console.error("bundle: no .luau sources found under src/ — nothing to test");
    process.exit(2);
}

const args = process.argv.slice(2);
let emitPath = null;
let only = null;
const wanted = [];
for (let i = 0; i < args.length; i += 1) {
    if (args[i] === "--emit") emitPath = args[++i];
    else if (args[i] === "--only") only = args[++i];
    else wanted.push(args[i]);
}

const specFiles = (wanted.length ? wanted : walk(SPEC_DIR))
    .map((p) => (p.includes("/") ? resolve(ROOT, p) : join(SPEC_DIR, p.endsWith(".luau") ? p : `${p}.spec.luau`)))
    .filter((p) => p.endsWith(".luau"));

if (specFiles.length === 0) {
    console.error("bundle: no spec files found under tests/specs");
    process.exit(2);
}

const parts = [];
parts.push("--!nolint");
parts.push("-- GENERATED by tests/tools/bundle.mjs — do not edit, do not commit.");
parts.push("local BUNDLE_ROOT = " + JSON.stringify(ROOT));

// 1. Mock Roblox environment. Each chunk receives the shared table `M` and fills in one layer:
//    datatypes -> instances -> services -> control surface. Order matters (later layers use
//    earlier ones), so it is fixed here rather than discovered from the directory listing.
const MOCK_ORDER = ["Json", "Datatypes", "Instances", "Services", "Roblox"];
parts.push("local M = {}");
for (const chunk of MOCK_ORDER) {
    parts.push(`;(function(M)`);
    parts.push(`--#region tests/mock/${chunk}.luau`);
    parts.push(prepare(readFileSync(join(MOCK_DIR, `${chunk}.luau`), "utf8")));
    parts.push(`--#endregion`);
    parts.push("end)(M)");
}
parts.push("local Mock = M.Mock");

// 2. Tiny assertion / runner library.
parts.push("local Testing = (function()");
parts.push(prepare(readFileSync(join(MOCK_DIR, "Testing.luau"), "utf8")));
parts.push("end)()");

// 3. Module registry: every source file as a closure keyed by its Rojo instance path.
parts.push("local MODULE_DEFS = {}");
parts.push("local MODULE_ORDER = {}");
for (const mod of modules) {
    const source = prepare(readFileSync(mod.file, "utf8"));
    parts.push(`MODULE_ORDER[#MODULE_ORDER + 1] = { Path = ${JSON.stringify(mod.path)}, Class = ${JSON.stringify(mod.class)}, File = ${JSON.stringify(relative(ROOT, mod.file))} }`);
    parts.push(`MODULE_DEFS[${JSON.stringify(mod.path)}] = function(script, require, ...)`);
    parts.push(`--#region ${relative(ROOT, mod.file)}`);
    parts.push(source);
    parts.push(`--#endregion`);
    parts.push("end");
}

// 4. Hand the registry to the mock so it can build the instance tree and serve require().
parts.push("Mock.installModules(MODULE_ORDER, MODULE_DEFS)");
parts.push("local loadModule = Mock.loadModule");
parts.push("local runScript = Mock.runScript");

// 5. Spec bodies.
parts.push("local SPECS = {}");
for (const spec of specFiles) {
    const name = basename(spec).replace(/\.luau$/, "");
    if (only && !name.includes(only)) continue;
    const source = prepare(readFileSync(spec, "utf8"));
    parts.push(`SPECS[#SPECS + 1] = { Name = ${JSON.stringify(name)}, Run = function(t, Mock, loadModule, runScript)`);
    parts.push(`--#region tests/specs/${basename(spec)}`);
    parts.push(source);
    parts.push(`--#endregion`);
    parts.push("end }");
}
parts.push("Testing.runAll(SPECS, Mock, loadModule, runScript)");

const bundle = parts.join("\n");
const outPath = emitPath ? resolve(ROOT, emitPath) : join(ROOT, ".bundle", "tests.luau");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, bundle, "utf8");

if (emitPath) {
    console.log(`bundle: wrote ${relative(ROOT, outPath)} (${modules.length} modules, ${specFiles.length} specs)`);
    process.exit(0);
}

const run = spawnSync(LUAU, [outPath], { stdio: "inherit" });
if (run.error) {
    console.error(`bundle: failed to run '${LUAU}' — set LUAU_BIN to your luau binary. ${run.error.message}`);
    process.exit(2);
}
process.exit(run.status === null ? 1 : run.status);
